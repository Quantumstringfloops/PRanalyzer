import time
import structlog
import re
from pr_analyzer.models import PRSummary, Suggestion ,AnalysisResult, QualityScore
from pr_analyzer.github.client import GithubClient
from pr_analyzer.analyzer.ast_analyzer import StaticAnalyzer
from pr_analyzer.security.scanner import SecurityScanner
from pr_analyzer.llm.engine import LLMEngine
from pr_analyzer.analyzer.scorer import Scorer
from pr_analyzer.config import settings

log = structlog.get_logger(__name__)
class AnalysisPipeline:
    def __init__(self):
            self.github   = GithubClient()
            self.static   = StaticAnalyzer()
            self.security = SecurityScanner()
            self.llm      = LLMEngine()
            self.scorer   = Scorer()

    def run(self, url: str, skip_llm: bool = False) -> AnalysisResult:
        start = time.time()


        log.info("Fetching PR")
        pr = self.github.fetch_pr(url)
        log.info("PR fetched succesfully", PR = pr)

        log.info("Static analysis starting..")
        static_analysis = self.static.analyze(pr.files)

        log.info("Security analysis starting..")
        security_analysis = self.security.scan(pr.files)

        existing_findings = static_analysis + security_analysis
        log.info("LLM analysis ..")

        llm_suggestions = []
        if not skip_llm:
            log.info("running LLM analysis")
            llm_suggestions = self.llm.analyze(pr, existing_findings)
            log.info("LLM analysis done", count=len(llm_suggestions))
        else:
            log.info("skipping LLM analysis")


        all_suggestions = llm_suggestions + static_analysis + security_analysis

        log.info("Scoring: ")
        score = self.scorer.score(all_suggestions)

        duration = round(time.time() - start, 2)

        log.info("pipeline complete",
                 score=score.overall_score,
                 grade=score.grade,
                 passed=score.passed,
                 duration=duration
        )
        return AnalysisResult(
            pr =pr,
            suggestions = all_suggestions,
            score=score,
            passed=score.passed,
            analysis_duration_seconds=duration,
            llm_provider_used=None if skip_llm else settings.llm_provider,
            )


    def run_and_post(self, url: str, skip_llm: bool = False) -> AnalysisResult:
        result = self.run(url, skip_llm=skip_llm)
        self._post_github_review(result)

        return result

    def _post_github_review(self, result: AnalysisResult) -> None:
        body = self._build_review_body(result)
        comments = self._map_suggestions_to_positions(result)

        log.info("posting github review", comments=len(comments))
        self.github.post_review(result.pr, body, comments)

    def _map_suggestions_to_positions(self, result: AnalysisResult) -> list[tuple]:
        # maps suggestion line numbers to diff positions for inline comments
        # diff position is the line count from the first @@ header in the patch
        positions = []

        for s in result.suggestions:
            if s.line is None:
                continue

            # find the file in pr.files
            file = next((f for f in result.pr.files if f.filename == s.filename), None)
            if file is None or file.patch is None:
                continue

            position = self._find_diff_position(file.patch, s.line)
            if position is not None:
                positions.append((s, position))

        return positions
    def _find_diff_position(self, patch: str, target_line: int) -> int | None:
        import re
        hunk_pattern = re.compile(r"@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")
        position = 0
        current_line = None

        for raw_line in patch.splitlines():
            # hunk header
            hunk_match = hunk_pattern.match(raw_line)
            if hunk_match:
                current_line = int(hunk_match.group(1))
                position += 1
                continue

            position += 1

            if raw_line.startswith("-"):
                continue  # deleted line — no new file line number

            if current_line == target_line:
                return position

            current_line += 1

        return None


    def _build_review_body(self, result: AnalysisResult) -> str:
        score = result.score
        status = "✅ PASSED" if score.passed else "❌ BLOCKED"

        lines = [
            f"## PR Analysis Report",
            f"",
            f"| Score | Grade | Status | Critical | High |",
            f"|-------|-------|--------|----------|------|",
            f"| {score.overall_score:.1f} | {score.grade} | {status} | {score.critical_count} | {score.high_count} |",
            f"",
            f"**Summary:** {score.summary}",
            f"",
            f"---",
            f"*Generated by pr-analyzer — {result.duration:.2f}s*",
        ]

        return "\n".join(lines)